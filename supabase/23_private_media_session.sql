-- ------------------------------------------------------------
--  (أ) تحويل المخزن إلى خاص وإزالة القراءة العامة
--
--  الرفع (insert) للمسجّلين يبقى كما هو. القراءة تتم حصريًا عبر
--  روابط موقّعة يولّدها الخادم بمفتاح service_role، فلا حاجة لأي
--  سياسة select — الرابط الموقّع يعمل بذاته ثم ينتهي.
-- ------------------------------------------------------------
update storage.buckets set public = false where id = 'project-media';

drop policy if exists "project_media_read"   on storage.objects;
drop policy if exists "project_media_public"  on storage.objects;
drop policy if exists "project-media read"     on storage.objects;

-- ------------------------------------------------------------
--  (ب) مفاتيح الإعدادات — عامة (أرقام غير حسّاسة) ليقرأها الوسيط
--     والواجهة بمفتاح anon.
--       media_link_minutes: مدة صلاحية رابط الوسائط بالدقائق.
--       session_minutes:    مدة الجلسة بالدقائق قبل طلب الدخول ثانية.
-- ------------------------------------------------------------
insert into public.app_settings(key, value, is_public) values
  ('media_link_minutes', '60',  true),
  ('session_minutes',    '480', true)
on conflict (key) do nothing;

